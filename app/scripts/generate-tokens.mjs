import { spawnSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import {
	breakpoints,
	darkTokens,
	textSizes,
	tokens,
} from "../src/design-system/tokens/theme.mjs";

function rule(selector, values) {
	return `${selector} {\n${Object.entries(values)
		.map(([name, value]) => `  --pf-${name}: ${value};`)
		.join("\n")}\n}\n`;
}

const directory = new URL("../src/design-system/generated/", import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(
	new URL("tokens.css", directory),
	`/* Generated by pnpm tokens:build. */\n${rule(":root", tokens)}${rule('[data-site-theme="dark"], [data-theme="dark"]', darkTokens)}@media (prefers-color-scheme: dark) {\n${rule('[data-site-theme="auto"]', darkTokens)}}\n${Object.entries(
		textSizes,
	)
		.map(([name, values]) => rule(`[data-text-size="${name}"]`, values))
		.join("\n")}`,
);
await writeFile(
	new URL("media.css", directory),
	`/* Generated by pnpm tokens:build. */\n${Object.entries(breakpoints)
		.map(([name, width]) => `@custom-media --${name} (min-width: ${width});`)
		.join("\n")}\n`,
);

for (const name of ["tokens.css", "media.css"]) {
	const file = new URL(name, directory);
	const formatted = spawnSync(
		"pnpm",
		["exec", "biome", "format", `--stdin-file-path=${name}`],
		{ input: await readFile(file, "utf8"), encoding: "utf8" },
	);
	if (formatted.error || formatted.status !== 0) {
		throw new Error("Design token formatting failed", {
			cause: formatted.error,
		});
	}
	await writeFile(file, formatted.stdout);
}
